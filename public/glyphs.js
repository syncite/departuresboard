// Tile-mosaic glyphs modelled on the SNCB departure boards (Brussel-Zuid, 2023).
//
// Each character is a grid of 5 columns (wide, narrow, wide, narrow, wide)
// by 10 rows: rows 0-7 are the cap height, 2-7 the x-height, 8-9 descenders.
